const candidate = (id: string, section: string[], text: string, extra: Partial<FilingPassageCandidate> = {}): FilingPassageCandidate =>
  ({ passage_id: id, source_id: "doc-a", title: "10-K", section_path: section, chunk_index: Number(id.replace(/\D/g, "")) || 0,
    text, document_rank: 0, ...extra });

test("sections and text that explain drivers score high; risk, intro and legal boilerplate score low", () => {
  assert.equal(sectionScore(["PART II", "Trends in Our Ad Impressions and Average Price Per Ad"]), 4);
  assert.equal(sectionScore(["PART II", "Family of Apps Metrics"]), 2);
  assert.equal(sectionScore(["Item 7. Management's Discussion and Analysis", "Results of Operations"]), 2);
  assert.equal(sectionScore(["PART II", "Family of Apps"]), 0, "a segment name alone says nothing; its text decides");
  assert.equal(sectionScore(["Item 1A. Risk Factors", "Results of operations may fluctuate"]), -4);
  assert.equal(sectionScore(["PART II—OTHER INFORMATION", "Risks Related to Our Business Operations and Financial Results"]), -4);
  assert.equal(sectionScore(["LIMITATIONS OF KEY METRICS AND OTHER DATA", "Family Metrics"]), -4);
  assert.equal(passageScore({ section_path: ["PART II", "Family of Apps"],
    text: "Revenue in 2025 increased 22% compared to 2024, driven by advertising. Ad impressions increased by 12% and average price per ad increased by 9%." }), 5);
  assert.ok(passageScore({ section_path: ["PART II", "Results of Operations"],
    text: "In this section, we discuss the results of our operations for 2025 compared to 2024." }) <= 0);
  assert.ok(passageScore({ section_path: ["Note 15. Segment Information"], text: "2025 | 2024\n189,458 | 162,355\n(19,190) | (17,729)" }) <= 0, "a number-only table");
});

// Section shapes from Meta's FY2025 10-K and an FY2022 10-K in run 7fa1f00a.
test("on real 10-K section shapes, segment, metric and trend discussion wins over intro boilerplate and older filings", () => {
  const items = [
    candidate("p1", ["PART II", "Results of Operations"], "In this section, we discuss the results of our operations for 2025 compared to 2024. For a discussion of 2024 compared to 2023, see our prior Annual Report."),
    candidate("p2", ["PART II", "Family of Apps"], "Revenue from Family of Apps increased 22% compared to 2024, driven by advertising. Advertising revenue grew due to a 12% increase in ad impressions and a 9% increase in average price per ad."),
    candidate("p3", ["PART II", "Trends in Our Ad Impressions and Average Price Per Ad"], "Ad Impressions. Our advertising revenue is generated by displaying ad products on Facebook, Instagram, Messenger, and third-party mobile applications. Average Price Per Ad. We calculate average price per ad as total advertising revenue divided by the number of ads delivered."),
    candidate("p4", ["PART II", "Family of Apps Metrics"], "Family daily active people (DAP) was 3.58 billion on average for December 2025, an increase of 7% year-over-year. Ad impressions increased by 12% year-over-year in 2025. Average price per ad increased by 9% year-over-year in 2025."),
    candidate("p5", ["PART II", "Trends in Our Family Metrics"], "Worldwide DAP increased 7% compared to the prior year, driven by growth in Asia-Pacific and Rest of World."),
    candidate("p6", ["PART II—OTHER INFORMATION", "Risks Related to Our Business Operations and Financial Results"], "Our revenue could decrease 10% or more if advertisers reduce spending, primarily due to macroeconomic conditions."),
    candidate("p7", ["NOTES TO CONSOLIDATED FINANCIAL STATEMENTS", "Note 17. Segment and Geographical Information"], "Revenue increased 1% compared to 2021, primarily due to growth in impressions.", { source_id: "doc-2022", document_rank: 3 }),
    candidate("p8", ["NOTES TO CONSOLIDATED FINANCIAL STATEMENTS", "Note 15. Segment and Geographical Information"], "Revenue increased 22% compared to 2024, primarily due to growth in impressions."),
  ];
  const ids = selectFilingPassages(items, 24_000).map(p => p.passage_id);
  for (const wanted of ["p2", "p3", "p4", "p5"]) assert.ok(ids.includes(wanted), `${wanted} is selected`);
  assert.ok(!ids.includes("p1") && !ids.includes("p6"), "intro and risk boilerplate are left out");
  assert.ok(ids.indexOf("p8") < ids.indexOf("p7"), "the FY2025 note ranks above the FY2022 one");
  assert.deepEqual(selectFilingPassages([...items].reverse(), 24_000).map(p => p.passage_id), ids, "input order does not matter");
});

