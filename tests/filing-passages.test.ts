test("selection stays within the byte budget, cuts long passages and limits each document", () => {
  const many = Array.from({ length: 30 }, (_, i) => candidate(`p${i}`, ["Results of Operations", `Topic ${i}`],
    "Revenue increased 5% due to higher volume. ".repeat(200), { source_id: `doc-${i % 3}`, claim_ids: ["c2", "c1"] }));
  for (const budget of [0, 500, 4_000, 9_000, 24_000]) {
    const chosen = selectFilingPassages(many, budget);
    assert.ok(Buffer.byteLength(JSON.stringify(chosen)) <= Math.max(budget, 2), `budget ${budget}`);
  }
  const chosen = selectFilingPassages(many, 1_000_000);
  assert.equal(chosen.length, 18, "six passages from each of three documents");
  assert.ok(chosen.every(p => p.text.length === 3_000), "each passage is cut to 3,000 characters");
  assert.deepEqual(chosen[0].claim_ids, ["c1", "c2"], "claim IDs are sorted");
  assert.equal(chosen[0].section, "Results of Operations / Topic 0");
  const repeated = [candidate("a1", ["PART II", "Family of Apps"], "Revenue increased 22% driven by ads.", { source_id: "q", document_rank: 0 }),
    candidate("b1", ["PART II", "Family of Apps"], "Revenue increased 22% driven by ads.", { source_id: "k", document_rank: 1 })];
  assert.deepEqual(selectFilingPassages(repeated, 10_000).map(p => p.passage_id), ["a1"], "the 10-K's copy of a 10-Q section is not repeated");
});

test("the byte budget comes from RESEARCH_FILING_PASSAGE_BYTES", () => {
  assert.equal(filingPassageBudget({}), 24_000);
  assert.equal(filingPassageBudget({ RESEARCH_FILING_PASSAGE_BYTES: "8000" }), 8_000);
  assert.equal(filingPassageBudget({ RESEARCH_FILING_PASSAGE_BYTES: "0" }), 0, "0 turns the passages off");
  assert.equal(filingPassageBudget({ RESEARCH_FILING_PASSAGE_BYTES: "lots" }), 24_000);
  assert.equal(filingPassageBudget({ RESEARCH_FILING_PASSAGE_BYTES: "-5" }), 24_000);
});

class ScriptedProvider implements ModelProvider {
  readonly id = "scripted";
  calls = 0;
  constructor(private readonly handler: (request: ModelRequest, call: number) => AsyncGenerator<ModelEvent>) {}
  stream(request: ModelRequest) { this.calls += 1; return this.handler(request, this.calls); }
}

test("the compacted fallback keeps the top filing passages instead of dropping them", async () => {
  const oldFallback = process.env.RESEARCH_EXPORT_WRITER_FALLBACK_MODEL;
  process.env.RESEARCH_EXPORT_WRITER_FALLBACK_MODEL = "fallback-model";
  const filing_passages = Array.from({ length: 10 }, (_, i) => ({ passage_id: `passage-${i}`, text: "MD&A ".repeat(50) }));
  const packets: string[] = [];
  const provider = new ScriptedProvider((request, call) => {
    packets.push(request.prompt);
    if (call === 1) return (async function* () { throw new ProviderError("network", "connection"); })();
    return (async function* () {
      yield { type: "response.started", requestId: "req" } as ModelEvent;
      yield { type: "text.delta", text: "{}" } as ModelEvent;
      yield { type: "response.completed", finishReason: "stop", usage: { inputTokens: 1, outputTokens: 1 } } as unknown as ModelEvent;
    })();
  });
  try {
    await runResearchAgent<any>({ agentName: "export-writer", title: "fallback", taskPacket: { filing_passages }, provider,
      outputFormat: { type: "json", requiredKeys: [] } as any, policy: { retryBaseDelayMs: 1 } }).catch(() => undefined);
    assert.ok(packets.length >= 2, "the fallback model was called");
    const kept = (prompt: string) => (prompt.match(/passage-\d+/g) || []).length;
    assert.equal(kept(packets[0]), 10);
    assert.equal(kept(packets[1]), 4, "the four best-ranked passages stay");
    assert.ok(packets[1].includes("passage-0") && !packets[1].includes("passage-4"));
  } finally {
    if (oldFallback === undefined) delete process.env.RESEARCH_EXPORT_WRITER_FALLBACK_MODEL;
    else process.env.RESEARCH_EXPORT_WRITER_FALLBACK_MODEL = oldFallback;
  }
});

test("a run's MD&A and segment passages are loaded with the accepted claims located in them", { skip }, async () => {
  const sql = postgres(process.env.DATABASE_URL!);
  const assetId = randomUUID(), runId = randomUUID();
  const ctx = { runId, runType: "deep_dive", assetId, assetName: "Passage Fixture Co", assetSlug: `passages-${assetId.slice(0, 8)}`, symbol: "PSGF",
    profileId: "", profileKey: "", requiredModules: [], requiredLenses: [], marketDataCutoffAt: null, pipelineVersion: 3 };
  const ids: string[] = [];
  try {
    await sql`INSERT INTO assets (id, canonical_name, slug, asset_kind, status, base_currency) VALUES (${assetId}, ${ctx.assetName}, ${ctx.assetSlug}, 'equity', 'active', 'USD')`;
    await sql`INSERT INTO research_runs (id, asset_id, run_type, status, source_cutoff_at, pipeline_version, budget_limit_usd)
      VALUES (${runId}, ${assetId}, 'deep_dive', 'running', '2026-10-01', 3, 10)`;
    const store = async (title: string, publishedAt: string, content: string) => {
      const [stored] = await storeDiscoveredSources(sql, ctx as any, [{ sourceType: "sec_filing_10-k", title, publisher: "passages.example",
        url: `https://passages.example/${randomUUID()}`, content, mimeType: "text/html", qualityScore: "0.9", publishedAt, periodEnd: publishedAt,
        metadata: { source_role: "regulatory_filing", system_generated: true }, chunkTitle: title }] as any);
      ids.push(String(stored.sourceId));
      return String(stored.sourceId);
    };
    const html = (sections: [string, string][]) => `<html><body>${sections.map(([h, p]) => `<h2>${h}</h2><p>${p} ${runId}</p>`).join("")}</body></html>`;
    const tenK = await store("10-K 2025", "2026-02-01", html([
      ["Item 1A. Risk Factors", "Our revenue could decrease if advertisers reduce spending."],
      ["Item 7. Management's Discussion and Analysis of Financial Condition and Results of Operations",
        "Revenue increased 22% compared to 2024, primarily driven by a 10% increase in ad impressions and a 11% increase in average price per ad."],
      ["Note 15. Segment Information", "Reportable segments: Family of Apps operating income was 87 billion; Reality Labs operating loss was 17 billion."],
    ]));
    const late = await store("10-Q 2026-12", "2026-12-15", html([["Item 2. Management's Discussion and Analysis", "Revenue increased 30% compared to the prior quarter, driven by pricing."]]));
    await loadFilingPassages(sql, runId, { maxBytes: 1 }); // indexes the documents into research-memory passages
    const [memory] = await sql`SELECT dc.id, dc.char_start, dc.char_end FROM document_chunks dc JOIN document_parses dp ON dp.id = dc.document_parse_id
      WHERE dc.source_document_id = ${tenK} AND dp.parser_name = 'research-memory' AND dc.text LIKE '%ad impressions%' LIMIT 1`;
    assert.ok(memory, "the 10-K is indexed into research-memory passages");
    const claim = randomUUID(), other = randomUUID();
    for (const id of [claim, other]) {
      await sql`INSERT INTO evidence_claims (id, research_run_id, asset_id, claim_text, claim_type, claim_category, generated_by, review_status)
        VALUES (${id}, ${runId}, ${assetId}, 'Revenue rose 22%', 'metric', 'fact', 'test', 'accepted')`;
      const [location] = await sql`INSERT INTO source_locations (source_document_id, document_chunk_id, char_start, char_end)
        VALUES (${tenK}, ${memory.id}, ${memory.char_start}, ${memory.char_end}) RETURNING id`;
      await sql`INSERT INTO evidence_links (evidence_claim_id, source_location_id, support_type, quoted_text) VALUES (${id}, ${location.id}, 'supports', 'Revenue increased 22%')`;
    }

    const passages = await loadFilingPassages(sql, runId, { cutoff: new Date("2026-10-01"), claimIds: [claim] });
    assert.ok(passages.length >= 2);
    assert.ok(passages.every(p => p.source_id !== late), "a filing published after the cutoff is left out");
    assert.match(passages[0].section, /Management's Discussion/, "MD&A ranks first");
    assert.deepEqual(passages[0].claim_ids, [claim], "only claims the packet carries are offered for citation");
    assert.ok(passages.some(p => /Segment Information/.test(p.section)));
    assert.ok(!passages.some(p => /Risk Factors/.test(p.section) && passages.indexOf(p) < 2), "risk factors do not lead");
    assert.deepEqual(await loadFilingPassages(sql, runId, { cutoff: new Date("2026-10-01"), claimIds: [claim] }), passages, "deterministic");
    assert.deepEqual(await loadFilingPassages(sql, runId, { maxBytes: 0 }), []);
  } finally {
    await sql`DELETE FROM evidence_links WHERE evidence_claim_id IN (SELECT id FROM evidence_claims WHERE research_run_id = ${runId})`;
    await sql`DELETE FROM evidence_claims WHERE research_run_id = ${runId}`;
    await sql`DELETE FROM research_run_sources WHERE research_run_id = ${runId} OR source_document_id = ANY(${ids}::uuid[])`;
    for (const table of ["source_locations", "document_chunks", "document_parses", "source_role_assignments"]) {
      await sql`DELETE FROM ${sql(table)} WHERE source_document_id = ANY(${ids}::uuid[])`;
    }
    await sql`DELETE FROM source_documents WHERE id = ANY(${ids}::uuid[])`;
    await sql`DELETE FROM research_runs WHERE id = ${runId}`;
    await sql`DELETE FROM assets WHERE id = ${assetId}`;
    await sql.end();
  }
});
